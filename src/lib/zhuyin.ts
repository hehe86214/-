export type ZhuyinChar = { char: string; zhuyin: string | null };

/**
 * 把文字拆成單字並附上注音；標點符號與非中文字回傳 zhuyin: null（不加注音）。
 * 「一」「個」的變調（一個 yí ge）會依前一個字自動判斷；
 * overrides 可用來指定特定位置的「一」讀音（例如量詞填空題，正確答案不在句子裡）。
 */
export function charsWithZhuyin(text: string, overrides?: Record<number, string>): ZhuyinChar[] {
  const chars = Array.from(text);
  return chars.map((char, i) => {
    if (overrides && overrides[i] !== undefined) {
      return { char, zhuyin: overrides[i] };
    }
    if (char === "個") {
      return { char, zhuyin: chars[i - 1] === "一" ? "ㄍㄜ˙" : "ㄍㄜˋ" };
    }
    if (char === "一") {
      if (chars[i + 1] === "個") return { char, zhuyin: "ㄧˊ" };
      const nextReading = chars[i + 1] ? ZHUYIN_DICT[chars[i + 1]] : undefined;
      if (!nextReading) return { char, zhuyin: "ㄧ" };
      return { char, zhuyin: nextReading.endsWith("ˋ") ? "ㄧˊ" : "ㄧˋ" };
    }
    return { char, zhuyin: ZHUYIN_DICT[char] ?? null };
  });
}
